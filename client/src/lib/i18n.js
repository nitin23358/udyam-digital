const DICTS = { en, hi };
export function makeT(lang) {
  const d = DICTS[lang] || en;
  return (key, params) => {
    let s = d[key] ?? en[key] ?? key;
    if (params) s = s.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '');
    return s;
  };
}
